CREATE TABLE IF NOT EXISTS player (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    role ENUM('FARMER', 'WOLF', 'OVERSEER') NOT NULL,
    is_alive BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS game_state (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_phase ENUM('NIGHT_WOLVES', 'NIGHT_SEER', 'DAY_DISCUSSION', 'DAY_VOTING') NOT NULL,
    round_number INTEGER NOT NULL DEFAULT 1,
    last_action_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS event_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_number INTEGER NOT NULL,
    phase_origin ENUM('NIGHT_WOLVES', 'NIGHT_SEER', 'DAY_DISCUSSION', 'DAY_VOTING') NOT NULL,
    actor_id INTEGER,
    target_id INTEGER,
    action_result VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_action_actor FOREIGN KEY (actor_id) REFERENCES player(id),
    CONSTRAINT fk_action_target FOREIGN KEY (target_id) REFERENCES player(id)
);
